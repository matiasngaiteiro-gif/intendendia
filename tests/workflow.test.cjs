const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.join(__dirname,'..');
const context=vm.createContext({Date,Intl,structuredClone,console});
vm.runInContext(fs.readFileSync(path.join(root,'contacts-data.js'),'utf8'),context);
vm.runInContext(fs.readFileSync(path.join(root,'app.js'),'utf8').replace(/bootstrap\(\);\s*$/,''),context);
