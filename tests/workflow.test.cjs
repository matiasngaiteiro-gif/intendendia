assert.equal((html.match(/id="newOrderBtn"/g)||[]).length,1);
assert.ok(html.indexOf('id="newOrderBtn"')>html.indexOf('id="ordersView"'));
// Regresión del formulario: ya no existen los controles title ni specialty.
const control=()=>({value:'',hidden:false,required:false,disabled:false,style:{},children:[],replaceChildren(){this.children=[]},append(option){this.children.push(option)}});
const form={elements:Object.fromEntries(['id','template','customTask','status','priority','assignee','category','description','building','dependency','location','dueDate'].map(key=>[key,control()])),reset(){Object.values(this.elements).forEach(c=>c.value='')}};
const nodes={'#orderForm':form,'#orderForm [name=assignee]':form.elements.assignee};
for(const name of ['customTaskLabel','orderModalTitle','deleteOrderBtn','finishOrderBtn','orderDialog'])nodes['#'+name]=control();
nodes['#orderDialog'].showModal=()=>{};
context.document={querySelector:selector=>nodes[selector],createElement:()=>control()};
context.openOrder();assert.equal(form.elements.customTask.disabled,true);
form.elements.template.value='Otra tarea';context.toggleCustomTask();
assert.equal(form.elements.customTask.required,true);assert.equal(nodes['#customTaskLabel'].hidden,false);
form.elements.template.value='Control de inventario';context.applyTemplate({target:form.elements.template});
assert.equal(form.elements.category.value,'Administrativo');assert.equal(form.elements.customTask.disabled,true);
